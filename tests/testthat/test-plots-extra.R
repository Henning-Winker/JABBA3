test_that("JAGG/JABBA plot set returns ggplots", {
  data(iccat); b <- iccat$bet
  d <- jb3_data(b$catch, b$cpue, b$se, stock = "bet")
  pr <- jb3_priors(d, r = c(0.2, 0.5), status = data.frame(year = 2010, type = "BBmsy", median = 1, log.sd = 0.3))
  f <- jabba3(d, pr, jb3_model(shape = "fox"), ndraws = 200)
  f2 <- jabba3(d, jb3_priors(d, r = c(0.2, 0.5)), jb3_model(shape = "schaefer"))
  pj <- jb3_project(f, catch = c(50000, 80000, 110000), nyears = 5)
  g <- function(x) expect_true(inherits(x, "ggplot") || inherits(x, "patchwork"))
  g(jbplot_advice(f, extra = c(Blim = 0.5), proj = pj, drop.last = TRUE))
  g(jbplot_trj(list(a = f, b = f2), nested = TRUE))
  g(jbplot_kobe(f, year = 2000))
  p <- jbplot_runs(f, mixing = "two.sided"); g(p); expect_true(is.data.frame(attr(p, "runs")))
  p <- jbplot_ppc(f); g(p); expect_true(all(attr(p, "ppc")$Bayesian.p >= 0 & attr(p, "ppc")$Bayesian.p <= 1))
  g(jbplot_stdresiduals(f)); g(jbplot_indices(f)); g(jbplot_biplot(f)); g(jbplot_biplot(f2))
  g(jbplot_catcherror(f)); g(jbplot_bprior(f)); expect_null(suppressMessages(jbplot_bprior(f2)))
  g(jbplot_ensemble(list(Fox = f, Schaefer = f2))); g(jbplot_ensemble(list(Fox = f, Schaefer = f2), joint = TRUE))
  g(jbplot_crisk(pj)); g(jbplot_summary(list(Fox = f, Schaefer = f2)))
  expect_error(jbplot_ebsb_status(f), "Selex")
  fs <- jabba3(d, jb3_priors(d, r = c(0.2, 0.5)), jb3_model(shape = "fox", ebsb = c(0.6, 1.2, 3, 0.1, 1)), osa = FALSE)
  g(jbplot_ebsb_status(fs))
})

test_that("jbplot_crisk ratio and named bfrac", {
  data(iccat); bet <- iccat$bet
  d <- jb3_data(bet$catch, bet$cpue, bet$se, stock = "bet")
  f <- jabba3(d, jb3_priors(d, r = c(0.2, 0.5)), jb3_model(shape = "fox"), osa = FALSE)
  m <- c(0.5, 1, 1.5)
  pr <- jb3_project(f, scenarios = setNames(lapply(m, function(v) c(Csq = v)), m), nyears = 5, ndraws = 100, imp.years = 1)
  expect_equal(unname(pr$sq["Csq"]), mean(tail(f$data$catch, 3)))
  g <- jbplot_crisk(pr, bfrac = c(MSST = 0.7), x = "ratio")
  expect_s3_class(g, "ggplot"); expect_equal(sort(unique(g$data$x)), m)
  expect_true("P(B < MSST)" %in% levels(g$data$risk))
  expect_error(jbplot_crisk(pr, years = 2050))
})

test_that("jbplot_projection reference points", {
  data(iccat); bet <- iccat$bet
  d <- jb3_data(bet$catch, bet$cpue, bet$se, stock = "bet")
  f <- jabba3(d, jb3_priors(d, r = c(0.2, 0.5)), jb3_model(shape = "fox"), osa = FALSE)
  pj <- jb3_project(f, fmsy = c(0.5, 1), nyears = 3, ndraws = 100)
  lab <- function(g) unlist(lapply(g$layers, function(l) if(inherits(l$geom, "GeomLabel")) as.character(l$data$name)))
  expect_true(all(c("Bmsy", "Fmsy", "MSY", "Bthr", "Blim") %in% lab(jbplot_projection(pj))))
  g <- jbplot_projection(pj, bthr = c(MSST = 0.8), blim = NULL, extra = c(Flim = 1.3))
  expect_true(all(c("MSST", "Flim") %in% lab(g))); expect_false("Blim" %in% lab(g))
  expect_null(lab(jbplot_projection(pj, refpts = FALSE)))
  expect_s3_class(jbplot_projection(pj, type = c("B", "F")), "ggplot")
})
