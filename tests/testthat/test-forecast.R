test_that("ensemble, fwdctrl, HCR and fishing opportunities table", {
  data(iccat); bet <- iccat$bet
  d <- jb3_data(bet$catch, bet$cpue, bet$se, stock = "bet"); pr <- jb3_priors(d, r = c(0.2, 0.5))
  runs <- list(Schaefer = jabba3(d, pr, jb3_model(shape = "schaefer"), osa = FALSE),
               Fox = jabba3(d, pr, jb3_model(shape = "fox"), osa = FALSE))
  w <- jb3_weights(runs); expect_equal(sum(w$weight), 1)
  ens <- jb3_ensemble(runs, weights = c(2, 1), ndraws = 300)
  expect_s3_class(ens, "jb3ensemble"); expect_equal(unname(ens$n), c(200, 100))
  expect_equal(nrow(ens$draws$B), 300)
  expect_s3_class(jbplot_advice(ens), "ggplot"); expect_s3_class(jbplot_kobe(ens), "ggplot")
  expect_s3_class(jbplot_ensemble(ens, kobe = FALSE), "ggplot")
  pe <- jb3_project(ens, fmsy = c(0.5, 1), nyears = 4); expect_equal(nrow(pe$iters[[1]]$B), 300)
  csq <- mean(tail(bet$catch[[2]], 3))
  fc <- list(Ftgt = data.frame(year = 2018:2021, value = c(csq, csq, 1, 1), quant = c("Catch", "Catch", "Fmsy", "Fmsy")),
             Csq = data.frame(year = 2018:2021, value = 1, quant = "Csq"))
  stf <- jb3_fwd(runs$Fox, fc, ndraws = 200)
  expect_equal(stf$tac.year, 2020)
  expect_true(all(abs(stf$iters$Ftgt$Catch[, 1] - csq) < 1e-6))
  expect_true(all(abs(stf$iters$Ftgt$`F/Fmsy`[, 3] - 1) < 1e-8))
  h <- jb3_hcr(stf); expect_s3_class(h, "jb3hcr"); expect_true(h$Fadv <= 1 && h$Fadv > 0)
  expect_s3_class(jbplot_hcr(h), "ggplot")
  expect_equal(.hockey(c(0, 0.25, 0.5, 2), 1, 0.5, 0, 0), c(0, 0.5, 1, 1))
  tb <- jb3_fwdtable(stf)
  expect_equal(names(tb), c("Basis", "C 2020", "F/Ftgt 2020", "B/Btgt 2021", "B change", "P(B>Blim)", "P(B>Bpa)", "P(B>Btgt)"))
  hc <- jb3_fwd(runs$Fox, data.frame(year = 2018:2020, value = c(csq, 1, 1), quant = c("Catch", "HCR", "HCR")), ndraws = 100)
  expect_true(all(hc$iters[[1]]$`F/Fmsy`[, 2] <= 1 + 1e-8))
  p0 <- jb3_project(runs$Fox, fmsy = 1, nyears = 5, imp.years = 2, ndraws = 100)
  expect_equal(p0$tac.year, 2020)
})
